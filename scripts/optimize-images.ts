function buildSite(home: ScrapePage, prev: ProjectsFile | null, showPricing: boolean): ProjectsFile["site"] {
  const previous = prev?.site;
  const footer = footerBlocks(home);
  const allText = home.text.textBlocks.map((b) => b.text).join("\n");
  const emailRe = /^[^\s@]+@[^\s@]+\.[a-z]{2,}$/i;
  const emailDisplayed = footer.find((b) => emailRe.test(b.text.trim()))?.text.trim() ?? previous?.emailDisplayed ?? "";
  if (!emailDisplayed) warn("home: no e-mail address found in the footer");
  const mailto = home.text.links?.mailto?.[0]?.replace(/^mailto:/i, "").split("?")[0]?.trim() ?? null;
  const emailMailto = mailto && emailRe.test(mailto) ? mailto : (previous?.emailMailto ?? null);
  const phone = footer.find((b) => /^[+\d][\d\s().-]{6,}$/.test(b.text.trim()))?.text.trim() ?? previous?.phone ?? null;
  let legalName = previous?.legalName ?? null;
  if (legalName && !allText.includes(legalName)) {
    warn(`site.legalName "${legalName}" does not occur in the scraped home copy — kept from the previous file, please verify`);
  } else if (!legalName) {
    const m = /\b(Style My Space (?:Inc\.|LLC|Design))/.exec(allText);
    legalName = m?.[1] ?? null;
  }
  const site = { legalName, emailDisplayed, emailMailto, phone, showPricing };
  compare("site.emailDisplayed", emailDisplayed, previous?.emailDisplayed);
  compare("site.emailMailto", emailMailto, previous?.emailMailto);
  compare("site.phone", phone, previous?.phone);
  return site;
}

