async function loadPage(slug: string): Promise<ScrapePage | null> {
  const file = path.join(PAGES_DIR, `${slug}.json`);
  if (!(await fileExists(file))) return null;
  const page = parseOrThrow(ScrapePageSchema, await readJson(file), rel(file));
  if (page.status !== 200) {
    warn(`${slug}: scraped with HTTP ${page.status} — treated as missing`);
    return null;
  }
  return page;
}

async function main(): Promise<void> {
  const args = parseArgs(process.argv.slice(2));
  const startedAt = Date.now();
  sharp.cache(false);

  // --- inputs -------------------------------------------------------------
  const report = parseOrThrow(ScrapeReportSchema, await readJson(path.join(SCRAPE_DIR, "scrape-report.json")), "scrape-report.json");
  const overrides = parseOrThrow(OverridesSchema, (await readJsonOptional(OVERRIDES_FILE)) ?? {}, "content/overrides.json");
  const altOverrides = parseOrThrow(AltOverridesSchema, (await readJsonOptional(ALT_OVERRIDES_FILE)) ?? {}, "content/alt-overrides.json");
  const manifestRaw = await readJsonOptional(MANIFEST_FILE);
  const manifestParsed = manifestRaw === undefined ? { success: true as const, data: {} } : ManifestSchema.safeParse(manifestRaw);
  if (!manifestParsed.success) warn("image-manifest.json is unreadable — rebuilding it (all images will be reconverted)");
  const manifest: Manifest = manifestParsed.success ? manifestParsed.data : {};

  let previous: ProjectsFile | null = null;
  const prevRaw = await readJsonOptional(CONTENT_FILE);
  if (prevRaw !== undefined) {
    const parsed = ProjectsFileSchema.safeParse(prevRaw);
    if (parsed.success) previous = parsed.data;
    else warn("existing content/projects.json does not validate — text fallbacks unavailable");
  }

  const home = await loadPage("home");
  if (!home) throw new Error("content/scrape/pages/home.json is missing — run pnpm content:scrape first");
  const portfolio = await loadPage("portfolio");
  const blogPage = await loadPage("blog");
  const bookOnline = await loadPage("book-online");
  const projectSlugs = report.pages.filter((p) => p.kind === "project").map((p) => p.slug);
  const postSlugs = report.pages.filter((p) => p.kind === "post").map((p) => p.slug);
  const posts = (await Promise.all(postSlugs.map(loadPage))).filter((p): p is ScrapePage => p !== null);
  if (args.only && !projectSlugs.includes(args.only) && args.only !== "blog" && args.only !== "site") {
    throw new Error(`--only=${args.only} is not a scraped project slug (${projectSlugs.join(", ")}), "blog" or "site"`);
  }

  // Portfolio order: /portfolio grid (cover mediaId → slug), else the scrape report's portfolioOrder, else scrape order.
  const pages = new Map<string, ScrapePage>();
  for (const slug of projectSlugs) {
    const page = await loadPage(slug);
    if (page) pages.set(slug, page);
    else warn(`${slug}: page JSON missing or not 200 — project omitted`);
  }
  const coverToSlug = new Map<string, string>();
  for (const [slug, page] of pages) for (const img of page.images) if (img.role === "cover") coverToSlug.set(img.mediaId, slug);
  const fromGrid = (portfolio?.images ?? []).map((i) => coverToSlug.get(i.mediaId)).filter((s): s is string => !!s);
  const orderSource = fromGrid.length === pages.size ? fromGrid : (report.sitemapCheck?.portfolioOrder ?? [...pages.keys()]);
  const order = [...new Set([...orderSource.filter((s) => pages.has(s)), ...pages.keys()])];
  if (orderSource !== fromGrid) warn("portfolio: could not derive the project order from the /portfolio grid — using the scrape report order");

  const converter = createConverter(manifest);
  const ctx: BuildContext = { args, converter, overrides, altOverrides, previous };

  // --- projects -----------------------------------------------------------
  const built: BuiltProject[] = [];
  for (const [i, slug] of order.entries()) built.push(await buildProject(ctx, pages.get(slug)!, i));
  const projects = built.map((b) => b.project);
  const rawFor = (ref: ImageRef): string | null => {
    const b = built.find((x) => x.project.slug === ref.slug);
    if (!b) return null;
    const i = b.project.images.findIndex((im) => im.mediaId === ref.mediaId);
    return i >= 0 ? (b.raws[i] ?? null) : null;
  };

  // OG per project (from the cover)
  await Promise.all(
    built.map(async ({ project, raws }) => {
      if (project.cover === null) return;
      const raw = raws[project.cover]!;
      const force = args.force && (!args.only || args.only === project.slug);
      const res = await converter.og(project.images[project.cover]!.mediaId, raw, path.join(PUBLIC_DIR, "projects", project.slug, "og.jpg"), force);
      summary.ogBytes += res.bytes;
    }),
  );

  // --- home refs (overrides) ----------------------------------------------
  const checkRef = (label: string, ref: ImageRef | null | undefined): ImageRef | null => {
    if (!ref) return null;
    if (rawFor(ref)) return ref;
    warn(`${label}: ${ref.slug}/${ref.mediaId} does not resolve to a generated image — set to null`);
    return null;
  };
  const hero = checkRef("home.hero", overrides.home?.hero);
  const manifesto = checkRef("home.manifesto", overrides.home?.manifesto);
  const materials = (overrides.home?.materials ?? []).map((m) => {
    if (m.image && !rawFor(m.image)) {
      throw new Error(`overrides.home.materials[${m.id}].image ${m.image.slug}/${m.image.mediaId} does not resolve to a generated image`);
    }
    return { id: m.id, label: m.label, quote: m.quote, quoteSource: m.quoteSource, image: m.image, objectPosition: m.objectPosition };
  });
  if (!materials.length) warn("home.materials is empty (overrides.home.materials not set)");

  // --- site assets ----------------------------------------------------------
  const forceSite = args.force && (!args.only || args.only === "site");
  const siteAssets: string[] = [];
  if (hero) {
    const raw = rawFor(hero)!;
    const res = await converter.og(hero.mediaId, raw, path.join(PUBLIC_DIR, "site", "og-home.jpg"), forceSite);
    summary.ogBytes += res.bytes;
    siteAssets.push("/site/og-home.jpg");
  } else warn("home.hero is null — public/site/og-home.jpg not generated");

  let portrait: SiteImage | null = null;
  const portraitImg = home.images.find((i) => i.role === "portrait");
  if (portraitImg?.download && (await fileExists(path.join(ROOT, portraitImg.download.path)))) {
    const rawAbs = path.join(ROOT, portraitImg.download.path);
    const outAbs = path.join(PUBLIC_DIR, "site", "portrait.webp");
    const m = await converter.master(portraitImg.mediaId, rawAbs, outAbs, forceSite);
    const rawBytes = await fileSize(rawAbs);
    summary.rawBytes += rawBytes;
    summary.webpBytes += m.bytes;
    portrait = {
      file: "/site/portrait.webp",
      mediaId: portraitImg.mediaId,
      sourceUrl: portraitImg.sourceUrl,
      width: m.width,
      height: m.height,
      originalWidth: m.originalWidth ?? portraitImg.originalWidth ?? m.width,
      originalHeight: m.originalHeight ?? portraitImg.originalHeight ?? m.height,
      blurDataURL: m.blurDataURL,
      alt: resolveAlt(altOverrides, portraitImg, "the designer portrait"),
      caption: resolveCaption(altOverrides, overrides, null, portraitImg),
      focalPoint: portraitImg.focalPoint,
    };
    siteAssets.push("/site/portrait.webp");
  } else warn("home: portrait not downloaded — meetTheDesigner.portrait is null");

  // --- text sections ---------------------------------------------------------
  const headline = home.text.h1[0]?.trim() || previous?.home.headline || "";
  if (!home.text.h1[0]?.trim()) warn("home: no <h1> scraped");
  compare("home.headline", headline, previous?.home.headline);
  const meetTheDesigner = buildMeetTheDesigner(home, previous, overrides.home?.pressConfirmed ?? false, portrait);
  const liveCards = buildLiveCards(home, previous);
  const recentProjects = order.filter((s) => projects.find((p) => p.slug === s)?.published !== false);
  const portfolioData = buildPortfolio(portfolio, previous);
  const { blog } = await buildBlog(ctx, blogPage, posts);
  const consultations = buildConsultations(bookOnline, previous);
  const site = buildSite(home, previous, overrides.site?.showPricing ?? true);

  // --- assemble + validate ---------------------------------------------------
  const data: ProjectsFile = {
    _generated: GENERATED_NOTE,
    generatedAt: new Date().toISOString(),
    source: SITE_URL,
    projects,
    home: { headline, hero, manifesto, materials, meetTheDesigner, liveCards, recentProjects },
    portfolio: portfolioData,
    blog,
    consultations,
    site,
    todos: [],
  };
  const todos: { token: string; path: string }[] = [];
  collectTodos(data, "", todos);
  data.todos = todos;

  const validated = ProjectsFileSchema.safeParse(data);
  if (!validated.success) {
    console.error("content/projects.json would be INVALID — not written:\n" + formatIssues(validated.error.issues));
    process.exitCode = 1;
    await writeFile(MANIFEST_FILE, JSON.stringify(manifest, null, 2) + "\n");
    return;
  }
  await writeFile(CONTENT_FILE, JSON.stringify(data, null, 2) + "\n");
  await writeFile(MANIFEST_FILE, JSON.stringify(manifest, null, 2) + "\n");
  summary.filesWritten.push(rel(CONTENT_FILE), rel(MANIFEST_FILE));

  await writeContactSheets(data);

  // --- report --------------------------------------------------------------
  const perProject = projects.map((p) => ({
    slug: p.slug,
    images: p.images.length,
    cover: p.cover,
    category: p.category,
    todoAlts: p.images.filter((i) => TODO_RE.test(i.alt)).length,
  }));
  log.info(
    `done in ${((Date.now() - startedAt) / 1000).toFixed(1)}s — ${summary.converted} converted, ${summary.skipped} up to date, ${summary.ogWritten} OG written; raw ${(summary.rawBytes / 1048576).toFixed(1)} MB → webp ${(summary.webpBytes / 1048576).toFixed(1)} MB; ${todos.length} TODO token(s)`,
  );
  console.log(
    "SUMMARY " +
      JSON.stringify({
        ok: true,
        projects: perProject,
        siteAssets,
        blog: blog.map((b) => ({ slug: b.slug, cover: b.cover?.file ?? null, body: b.body?.length ?? null })),
        todosTotal: todos.length,
        rawBytes: summary.rawBytes,
        webpBytes: summary.webpBytes,
        ogBytes: summary.ogBytes,
        converted: summary.converted,
        skipped: summary.skipped,
        contactSheets: summary.contactSheets,
        diffs: summary.diffs,
        warnings: summary.warnings,
        filesWritten: summary.filesWritten,
      }),
  );
}

