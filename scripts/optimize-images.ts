/**
 * Image optimisation + content generation.
 *
 *   pnpm content:images [--force] [--only=<slug>]
 *
 * Inputs (read-only): content/scrape/pages/<slug>.json + scrape-report.json (from scripts/scrape.ts), the raw
 * originals under content/raw/**, content/overrides.json and content/alt-overrides.json (lead-authored).
 *
 * Outputs (owned by this script):
 *   public/projects/<slug>/NN-<hex>.webp   WebP master (long edge ≤ 2400, q82) per project image, NN = page order
 *   public/projects/<slug>/og.jpg          1200×630 OG crop of the cover
 *   public/site/portrait.webp              Meet-the-Designer portrait, public/site/og-home.jpg from overrides.home.hero
 *   public/blog/<postslug>.webp            blog covers
 *   content/projects.json                  validated against src/lib/content.schema.ts (ProjectsFileSchema)
 *   content/scrape/image-manifest.json     mediaId → { rawSha1, settingsHash, outputs[] } for idempotent reruns
 *   qa/contact-sheets/images/<slug>.png    labelled thumbnails for alt-text authoring (+ site.png)
 *
 * Nothing is invented: missing content is logged (and, for alt text, left as a {{TODO: …}} token collected in todos[]).
 * The file name uses the 32-hex part of the media id because ImageSchema.file forbids "_" in path segments.
 */
