async function writeContactSheets(data: ProjectsFile): Promise<void> {
  await mkdir(SHEETS_DIR, { recursive: true });
  const label = (i: number, img: SiteImage) =>
    `${pad2(i)} · ${img.mediaId} · ${img.width}x${img.height} · ${img.alt.length > 64 ? `${img.alt.slice(0, 63)}…` : img.alt}`;
  for (const p of data.projects) {
    if (!p.images.length) continue;
    const images = p.images.map((img, i) => ({ path: path.join(PUBLIC_DIR, img.file), label: label(i, img) }));
    try {
      const res = await makeContactSheet({
        images,
        out: path.join(SHEETS_DIR, `${p.slug}.png`),
        title: `${p.slug} — ${p.images.length} image(s), cover=${p.cover ?? "null"}`,
      });
      summary.contactSheets.push(...res.files.map(rel));
    } catch (err) {
      warn(`contact sheet for ${p.slug} failed: ${errorMessage(err)}`);
    }
  }
  const site: { path: string; label: string }[] = [];
  const portrait = data.home.meetTheDesigner.portrait;
  if (portrait) site.push({ path: path.join(PUBLIC_DIR, portrait.file), label: `portrait · ${label(0, portrait).slice(5)}` });
  data.blog.forEach((b, i) => {
    if (b.cover) site.push({ path: path.join(PUBLIC_DIR, b.cover.file), label: `blog/${b.slug} · ${label(i, b.cover).slice(5)}` });
  });
  if (site.length) {
    try {
      const res = await makeContactSheet({ images: site, out: path.join(SHEETS_DIR, "site.png"), title: `site assets — ${site.length}` });
      summary.contactSheets.push(...res.files.map(rel));
    } catch (err) {
      warn(`site contact sheet failed: ${errorMessage(err)}`);
    }
  }
}

