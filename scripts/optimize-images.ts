interface BuildContext {
  args: Args;
  converter: Converter;
  overrides: Overrides;
  altOverrides: AltOverrides;
  previous: ProjectsFile | null;
}

interface BuiltProject {
  project: Project;
  /** raw path per built image (parallel to project.images) — used for OG generation */
  raws: string[];
}

async function buildProject(ctx: BuildContext, page: ScrapePage, order: number): Promise<BuiltProject> {
  const slug = page.slug;
  const prev = ctx.previous?.projects.find((p) => p.slug === slug);
  const ov = ctx.overrides.projects?.[slug];
  const force = ctx.args.force && (!ctx.args.only || ctx.args.only === slug);

  const title = page.text.h1[0]?.trim() || prev?.title || "";
  if (!page.text.h1[0]?.trim()) warn(`${slug}: no <h1> scraped; using previous title "${title}"`);
  compare(`projects.${slug}.title`, title, prev?.title);

  const description = page.description?.chosen?.trim() || page.text.meta.description?.trim() || prev?.description || "";
  if (!description) warn(`${slug}: no description scraped or previously recorded`);
  compare(`projects.${slug}.description`, description, prev?.description);

  // category
  let category: Project["category"] = null;
  let categorySource: Project["categorySource"] = "none";
  if (ov && "category" in ov && ov.category !== undefined) {
    category = ov.category;
    categorySource = "override";
  } else if (page.text.category) {
    const parsed = CategorySchema.safeParse(page.text.category.trim());
    if (parsed.success) {
      category = parsed.data;
      categorySource = "site";
    } else warn(`${slug}: scraped category "${page.text.category}" is not one of ${CategorySchema.options.join("/")} — ignored`);
  }
  const categoryNote = ov?.categoryNote ?? null;
  compare(`projects.${slug}.category`, category, prev?.category);
  compare(`projects.${slug}.categoryNote`, categoryNote, prev?.categoryNote);

  // images (page order; only cover|gallery roles belong to a project)
  const candidates = [...page.images].sort((a, b) => a.index - b.index);
  const jobs: { img: ScrapeImage; role: ProjectImage["role"]; rawAbs: string; nn: string; outAbs: string }[] = [];
  for (const img of candidates) {
    if (img.role !== "cover" && img.role !== "gallery") {
      warn(`${slug}: image ${img.mediaId} has role "${img.role}" — not a project image, skipped`);
      continue;
    }
    if (!img.download) {
      warn(`${slug}: image ${img.mediaId} (index ${img.index}) was not downloaded — omitted (nothing invented)`);
      continue;
    }
    const rawAbs = path.join(ROOT, img.download.path);
    if (!(await fileExists(rawAbs))) {
      warn(`${slug}: raw file missing ${img.download.path} — image ${img.mediaId} omitted`);
      continue;
    }
    const nn = pad2(img.index);
    jobs.push({ img, role: img.role, rawAbs, nn, outAbs: path.join(PUBLIC_DIR, "projects", slug, `${nn}-${hexOf(img.mediaId)}.webp`) });
  }
  // Promise.all keeps page order regardless of conversion concurrency.
  const images: ProjectImage[] = await Promise.all(
    jobs.map(async ({ img, role, rawAbs, nn, outAbs }): Promise<ProjectImage> => {
      const m = await ctx.converter.master(img.mediaId, rawAbs, outAbs, force);
      const rawBytes = await fileSize(rawAbs); // await first: `x += await y` would read x before the await
      summary.rawBytes += rawBytes;
      summary.webpBytes += m.bytes;
      return {
        file: `/projects/${slug}/${nn}-${hexOf(img.mediaId)}.webp`,
        mediaId: img.mediaId,
        sourceUrl: img.sourceUrl,
        width: m.width,
        height: m.height,
        originalWidth: m.originalWidth ?? img.originalWidth ?? img.download?.width ?? m.width,
        originalHeight: m.originalHeight ?? img.originalHeight ?? img.download?.height ?? m.height,
        blurDataURL: m.blurDataURL,
        alt: resolveAlt(ctx.altOverrides, img, `${slug} image ${nn}`),
        caption: resolveCaption(ctx.altOverrides, ctx.overrides, slug, img),
        focalPoint: img.focalPoint,
        role,
        source: img.source === "dom-only" ? "dom-only" : "warmup",
      };
    }),
  );
  const raws = jobs.map((j) => j.rawAbs);
  if (!images.length) warn(`${slug}: no images (page had ${page.images.length} records)`);

  // cover
  let cover: number | null = null;
  if (ov?.cover) {
    const i = images.findIndex((im) => im.mediaId === ov.cover);
    if (i >= 0) cover = i;
    else warn(`${slug}: overrides cover ${ov.cover} is not among the project's images — falling back to the cover gallery item`);
  }
  if (cover === null) {
    const i = images.findIndex((im) => im.role === "cover");
    cover = i >= 0 ? i : images.length ? 0 : null;
  }

  const project: Project = {
    slug,
    title,
    category,
    categorySource,
    categoryNote,
    description,
    sourceUrl: page.url,
    order,
    cover,
    published: ov?.published ?? true,
    images,
  };
  return { project, raws };
}

