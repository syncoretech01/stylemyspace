interface MasterResult {
  width: number;
  height: number;
  bytes: number;
  blurDataURL: string;
  originalWidth: number | null;
  originalHeight: number | null;
}

interface Converter {
  master(mediaId: string, rawAbs: string, outAbs: string, force: boolean): Promise<MasterResult>;
  og(mediaId: string, rawAbs: string, outAbs: string, force: boolean): Promise<{ bytes: number }>;
}

function createConverter(manifest: Manifest): Converter {
  const limit = pLimit(3);
  const shaCache = new Map<string, Promise<string>>();
  const rawSha = (file: string) => {
    let p = shaCache.get(file);
    if (!p) {
      p = sha1File(file);
      shaCache.set(file, p);
    }
    return p;
  };

  const entryFor = async (mediaId: string, rawAbs: string): Promise<{ entry: ManifestEntry; fresh: boolean }> => {
    const sha = await rawSha(rawAbs);
    const existing = manifest[mediaId];
    if (existing && existing.rawSha1 === sha && existing.settingsHash === MASTER_HASH) return { entry: existing, fresh: false };
    const entry: ManifestEntry = {
      rawPath: rel(rawAbs),
      rawSha1: sha,
      settingsHash: MASTER_HASH,
      originalWidth: existing && existing.rawSha1 === sha ? existing.originalWidth : null,
      originalHeight: existing && existing.rawSha1 === sha ? existing.originalHeight : null,
      // keep outputs from the same raw (they are re-validated per output settings hash)
      outputs: existing && existing.rawSha1 === sha ? existing.outputs : [],
    };
    manifest[mediaId] = entry;
    return { entry, fresh: true };
  };

  const upsertOutput = (entry: ManifestEntry, out: ManifestOutput) => {
    entry.outputs = entry.outputs.filter((o) => !(o.kind === out.kind && o.path === out.path));
    entry.outputs.push(out);
  };

  const originalDims = async (entry: ManifestEntry, rawAbs: string) => {
    if (entry.originalWidth && entry.originalHeight) return;
    try {
      const meta = await sharp(rawAbs, { limitInputPixels: false }).metadata();
      const swap = (meta.orientation ?? 1) >= 5;
      entry.originalWidth = (swap ? meta.height : meta.width) ?? null;
      entry.originalHeight = (swap ? meta.width : meta.height) ?? null;
    } catch (err) {
      warn(`metadata() failed for ${rel(rawAbs)}: ${errorMessage(err)}`);
    }
  };

  return {
    master: (mediaId, rawAbs, outAbs, force) =>
      limit(async () => {
        const { entry } = await entryFor(mediaId, rawAbs);
        const outRel = rel(outAbs);
        const cached = entry.outputs.find((o) => o.kind === "webp" && o.path === outRel);
        if (!force && cached && cached.settingsHash === MASTER_HASH && cached.blurDataURL && (await fileExists(outAbs))) {
          summary.skipped++;
          log.debug(`skip (up to date) ${outRel}`);
          return {
            width: cached.width,
            height: cached.height,
            bytes: cached.bytes,
            blurDataURL: cached.blurDataURL,
            originalWidth: entry.originalWidth,
            originalHeight: entry.originalHeight,
          };
        }
        const t0 = Date.now();
        await originalDims(entry, rawAbs);
        await mkdir(path.dirname(outAbs), { recursive: true });
        const { data, info } = await sharp(rawAbs, { limitInputPixels: false })
          .rotate()
          .resize({ width: SETTINGS.master.maxEdge, height: SETTINGS.master.maxEdge, fit: "inside", withoutEnlargement: true })
          .webp({ quality: SETTINGS.master.quality, effort: SETTINGS.master.effort })
          .toBuffer({ resolveWithObject: true });
        await writeFile(outAbs, data);
        const blur = await sharp(data).resize({ width: SETTINGS.blur.width }).webp({ quality: SETTINGS.blur.quality }).toBuffer();
        const blurDataURL = `data:image/webp;base64,${blur.toString("base64")}`;
        const out: ManifestOutput = {
          kind: "webp",
          path: outRel,
          width: info.width,
          height: info.height,
          bytes: info.size,
          settingsHash: MASTER_HASH,
          blurDataURL,
        };
        upsertOutput(entry, out);
        summary.converted++;
        summary.filesWritten.push(outRel);
        log.info(`wrote ${outRel} ${info.width}x${info.height} ${(info.size / 1024).toFixed(0)} KB (${Date.now() - t0} ms)`);
        return {
          width: info.width,
          height: info.height,
          bytes: info.size,
          blurDataURL,
          originalWidth: entry.originalWidth,
          originalHeight: entry.originalHeight,
        };
      }),
    og: (mediaId, rawAbs, outAbs, force) =>
      limit(async () => {
        const { entry } = await entryFor(mediaId, rawAbs);
        const outRel = rel(outAbs);
        const cached = entry.outputs.find((o) => o.kind === "og" && o.path === outRel);
        if (!force && cached && cached.settingsHash === OG_HASH && (await fileExists(outAbs))) {
          log.debug(`skip (up to date) ${outRel}`);
          return { bytes: cached.bytes };
        }
        await mkdir(path.dirname(outAbs), { recursive: true });
        const info = await sharp(rawAbs, { limitInputPixels: false })
          .rotate()
          .resize(SETTINGS.og.width, SETTINGS.og.height, { fit: "cover", position: sharp.strategy.attention })
          .jpeg({ quality: SETTINGS.og.quality, mozjpeg: true })
          .toFile(outAbs);
        upsertOutput(entry, { kind: "og", path: outRel, width: info.width, height: info.height, bytes: info.size, settingsHash: OG_HASH });
        summary.ogWritten++;
        summary.filesWritten.push(outRel);
        log.info(`wrote ${outRel} ${info.width}x${info.height} ${(info.size / 1024).toFixed(0)} KB`);
        return { bytes: info.size };
      }),
  };
}

