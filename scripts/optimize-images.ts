interface Args {
  force: boolean;
  only: string | null;
}

function parseArgs(argv: string[]): Args {
  const args: Args = { force: false, only: null };
  for (const a of argv) {
    if (a === "--force") args.force = true;
    else if (a.startsWith("--only=")) args.only = a.slice(7) || null;
    else throw new Error(`unknown argument ${a}`);
  }
  return args;
}

