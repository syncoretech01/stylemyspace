async function fileExists(file: string): Promise<boolean> {
  try {
    return (await stat(file)).isFile();
  } catch {
    return false;
  }
}

async function fileSize(file: string): Promise<number> {
  try {
    return (await stat(file)).size;
  } catch {
    return 0;
  }
}

async function sha1File(file: string): Promise<string> {
  const hash = createHash("sha1");
  for await (const chunk of createReadStream(file)) hash.update(chunk as Buffer);
  return hash.digest("hex");
}

async function readJson(file: string): Promise<unknown> {
  return JSON.parse(await readFile(file, "utf8")) as unknown;
}

async function readJsonOptional(file: string): Promise<unknown | undefined> {
  if (!(await fileExists(file))) return undefined;
  return readJson(file);
}

const rel = (abs: string) => path.relative(ROOT, abs);
const pad2 = (n: number) => String(n).padStart(2, "0");
/** "6af838_707a3b…" → "707a3b…" (ImageSchema.file forbids "_" in path segments). */
const hexOf = (mediaId: string) => mediaId.replace(/^[0-9a-f]{6}_/, "");
const FILENAME_RE = /\.(jpe?g|png|gif|webp|avif|tiff?|heic)$/i;
const TODO_RE = /\{\{TODO/;

function formatIssues(issues: { path: PropertyKey[]; message: string }[]): string {
  return issues.map((i) => `  ${i.path.map(String).join(".") || "<root>"}: ${i.message}`).join("\n");
}

function parseOrThrow<T>(schema: z.ZodType<T>, value: unknown, what: string): T {
  const res = schema.safeParse(value);
  if (!res.success) throw new Error(`${what} is invalid:\n${formatIssues(res.error.issues)}`);
  return res.data;
}

