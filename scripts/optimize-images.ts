const summary: Summary = {
  converted: 0,
  skipped: 0,
  ogWritten: 0,
  rawBytes: 0,
  webpBytes: 0,
  ogBytes: 0,
  diffs: [],
  warnings: [],
  contactSheets: [],
  filesWritten: [],
};

const warned = new Set<string>();
const warn = (msg: string) => {
  if (warned.has(msg)) return;
  warned.add(msg);
  log.warn(msg);
  summary.warnings.push(msg);
};

/** Log a difference between scraped text and the previous projects.json value (scraped wins). */
function compare(label: string, scraped: unknown, previous: unknown): void {
  if (previous === undefined) return;
  if (JSON.stringify(scraped) === JSON.stringify(previous)) return;
  const msg = `${label}: scraped value differs from the previous projects.json — keeping scraped. previous=${JSON.stringify(previous)} scraped=${JSON.stringify(scraped)}`;
  log.info(msg);
  summary.diffs.push(msg);
}

