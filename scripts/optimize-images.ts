function collectTodos(value: unknown, at: string, out: { token: string; path: string }[]): void {
  if (typeof value === "string") {
    if (TODO_RE.test(value)) out.push({ token: value, path: at });
  } else if (Array.isArray(value)) {
    value.forEach((v, i) => collectTodos(v, `${at}[${i}]`, out));
  } else if (value && typeof value === "object") {
    for (const [k, v] of Object.entries(value)) {
      if (at === "" && k === "todos") continue;
      collectTodos(v, at ? `${at}.${k}` : k, out);
    }
  }
}

