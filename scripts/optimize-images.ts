/** warmup caption = title || alt, ignoring empty strings and raw file names ("Photo.jpeg"). */
function warmupCaption(img: ScrapeImage): string | null {
  const raw = (img.caption ?? "").trim() || (img.alt ?? "").trim();
  if (!raw) return null;
  if (FILENAME_RE.test(raw)) {
    warn(`caption for ${img.mediaId} looks like a file name ("${raw}") — not used as alt text`);
    return null;
  }
  return raw;
}

function resolveAlt(altOverrides: AltOverrides, img: ScrapeImage, where: string): string {
  const ov = altOverrides[img.mediaId];
  if (ov?.alt && ov.alt.trim()) return ov.alt.trim();
  const cap = warmupCaption(img);
  if (cap) return cap;
  return `{{TODO: alt text for ${where} (${img.mediaId})}}`;
}

function resolveCaption(altOverrides: AltOverrides, overrides: Overrides, slug: string | null, img: ScrapeImage): string | null {
  const ov = altOverrides[img.mediaId];
  if (ov && "caption" in ov && ov.caption !== undefined) return ov.caption;
  const captions = slug ? overrides.projects?.[slug]?.captions : undefined;
  if (captions && Object.prototype.hasOwnProperty.call(captions, img.mediaId)) return captions[img.mediaId] ?? null;
  return warmupCaption(img);
}

